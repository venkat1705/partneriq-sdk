// Writes the developer portal's type reference (developer/src/data/sdk-types.generated.ts)
// from shared-types, so the docs show exactly what the SDK exports.
// Usage: node scripts/export-docs-types.mjs ../developer/src/data/sdk-types.generated.ts
import { readFileSync, writeFileSync } from 'node:fs';

const target = process.argv[2];
if (!target) throw new Error('Pass the output path, e.g. ../developer/src/data/sdk-types.generated.ts');

const src = readFileSync(new URL('../shared-types/src/index.ts', import.meta.url), 'utf8');

/** One exported declaration (with its leading doc comment) by name. */
function declaration(name) {
  const start = src.search(new RegExp(`^export (interface|type) ${name}\\b`, 'm'));
  if (start === -1) throw new Error(`Type ${name} not found`);
  // Include the JSDoc block only when it sits directly above the declaration.
  const before = src.slice(0, start);
  const docStart = before.lastIndexOf('/**');
  const hasDoc = docStart !== -1 && /^\/\*\*[\s\S]*\*\/\n$/.test(before.slice(docStart)) && !before.slice(docStart).includes('\n\n');
  const from = hasDoc ? docStart : start;
  // A declaration ends at the first blank line after it.
  const end = src.indexOf('\n\n', start);
  return src.slice(from, end === -1 ? undefined : end).trimEnd();
}

const sections = [
  ['options', 'Request options', ['PartnerIQRequestOptions']],
  ['conversions', 'Conversions & refunds', ['ConversionCreateRequest', 'RefundCreateRequest', 'Conversion', 'ConversionCreateResponse']],
  ['customers', 'Customers & attribution', ['IdentifyCustomerRequest', 'IdentifyCustomerResponse', 'AttachOrderRequest', 'AttachOrderResponse']],
  ['tracking', 'Tracking links, programs & affiliates', ['TrackingLinkCreateRequest', 'TrackingLinkListParams', 'TrackingLink', 'Program', 'Affiliate', 'Page']],
  ['webhooks', 'Webhooks', ['WebhookEventType', 'WebhookEndpointCreateRequest', 'WebhookEndpoint', 'WebhookEndpointWithSecret', 'WebhookEvent']],
].map(([id, title, names]) => ({ id, title, code: names.map(declaration).join('\n\n') }));

writeFileSync(
  target,
  `// GENERATED by sdk/scripts/export-docs-types.mjs from @partneriq-io/shared-types. Do not edit.\n` +
    `export const sdkTypeSections: Array<{ id: string; title: string; code: string }> = ${JSON.stringify(sections, null, 2)};\n`,
);
console.log(sections.map((s) => `${s.id}: ${s.code.split('\n').length} lines`).join(', '));
