// Regenerates @partneriq-io/shared-types from the Node SDK's request/response
// types, so the two can never drift. `--check` fails (CI) instead of writing.
import { readFileSync, writeFileSync } from 'node:fs';

const source = readFileSync(new URL('../partneriq-node/src/index.ts', import.meta.url), 'utf8');
const start = source.indexOf('// Request types');
const end = source.indexOf('// Errors');
if (start === -1 || end === -1) throw new Error('Type section markers not found in partneriq-node/src/index.ts');

const body = source
  .slice(source.lastIndexOf('\n', start) + 1, source.lastIndexOf('// ----', end))
  .trimEnd();
const output = `// GENERATED by scripts/sync-shared-types.mjs from partneriq-node/src/index.ts. Do not edit.

export type PartnerIQEnvironment = 'test' | 'live';

export interface PartnerIQErrorPayload {
  code: string;
  message: string;
  requestId?: string;
  details?: unknown;
}

${body}
`;

const target = new URL('../shared-types/src/index.ts', import.meta.url);
if (process.argv.includes('--check')) {
  if (readFileSync(target, 'utf8') !== output) {
    console.error('shared-types is out of date. Run: npm run sync:types');
    process.exit(1);
  }
} else {
  writeFileSync(target, output);
}
